  function translateShell() {
    // Only explicitly marked template text is translated, once. Dynamic case
    // records, report values, account names and evidence remain untouched.
    for (const element of document.querySelectorAll("[data-ui-copy]")) {
      const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
      let item;
      while ((item = walker.nextNode())) {
        if (item.parentElement.closest("[data-user-content],script,style")) continue;
        const original = item.textContent;
        const trimmed = original.trim();
        if (trimmed) {
          const translated = item.parentElement.tagName === "TITLE" ? trimmed.split(" | ").map(text).join(" | ") : text(trimmed);
          item.textContent = original.replace(trimmed, translated);
        }
      }
    }
    for (const element of document.querySelectorAll("[data-ui-attributes]")) {
      for (const attribute of ["aria-label", "placeholder", "title", "content"]) {
        if (element.hasAttribute(attribute)) element.setAttribute(attribute, text(element.getAttribute(attribute)));
      }
    }
    for (const toggle of document.querySelectorAll("[data-language-toggle]")) {
      toggle.textContent = language === "ar" ? "English" : "العربية";
      toggle.lang = language === "ar" ? "en" : "ar";
      toggle.setAttribute("aria-label", language === "ar" ? "Switch interface to English" : "تغيير لغة الواجهة إلى العربية");
      toggle.addEventListener("click", () => {
        const next = language === "ar" ? "en" : "ar";
        try { localStorage.setItem(storageKey, next); } catch (_) { return; }
        window.location.reload();
      });
    }
  }
  window.SOCifyLocale = Object.freeze({ language, text, template, error });
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", translateShell, { once: true });
  else translateShell();
